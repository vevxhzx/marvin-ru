export const I18nCtx = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(getLang)
  useEffect(() => {
    const h = (e) => setLangState(e.detail?.lang || getLang())
    window.addEventListener('i18n:lang', h)
    return () => window.removeEventListener('i18n:lang', h)
  }, [])
  const setLang = useCallback((l) => setLangState(setLangImpl(l)), [])
  const value = useMemo(() => ({
    t, lang, setLang, locale: localeOf(lang),
    fmtDate, fmtNumber, fmtMoney, fmtMoneyShort, fmtTime, fmtWeekday, fmtAgo, fmtList, plural, translateServerValue,
  }), [lang, setLang])
  return createElement(I18nCtx.Provider, { value }, children)
}

export function useI18n() {
  const ctx = useContext(I18nCtx)
  if (ctx) return ctx
  // вне провайдера (тесты/скрипты) — работающий дефолт на русском
  return {
    t, lang: getLang(), setLang: setLangImpl, locale: localeOf(), fmtDate, fmtNumber, fmtMoney,
    fmtMoneyShort, fmtTime, fmtWeekday, fmtAgo, fmtList, plural, translateServerValue,
  }
}
export const setLang = setLangImpl