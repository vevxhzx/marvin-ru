/* Совсем неизвестный ключ: humanize превращает его в читаемые слова,
   чтобы в интерфейсе не появлялось «zzz_unknown_key». */
const humanize = (key) => {
  const words = String(key).replace(/[._-]+/g, ' ').trim()
  return words ? words[0].toUpperCase() + words.slice(1) : String(key)
}

/* t('nav.today') · t('finance.debt_count', { count: 5 }) · t.status_paid */
export function translate(key, params) {
  if (key == null) return ''
  const entry = DICT[key] || SERVER[key]
  if (!entry) {
    const seg = String(key).split(/[._]/).pop()
    return segRu()[seg] || humanize(key)
  }
  const forms = entry[_lang] != null ? entry[_lang] : (entry[DEFAULT_LANG] ?? '')
  if (Array.isArray(forms)) return fill(plural(params?.count ?? 0, forms, _lang), params)
  return fill(forms, params)
}

/* Словари серверных значений: ищем точное совпадение значения в нормализованном виде. */
const fold = (s) => String(s ?? '').trim().toLowerCase().replace(/ё/g, 'е')
const SERVER_IDX = (() => {
  const idx = new Map()
  for (const k of Object.keys(SERVER)) {
    const ru = fold(SERVER[k].ru)
    if (!idx.has(ru)) idx.set(ru, k)
  }
  return idx
})()

/* Перевести значение, пришедшее с сервера: t.sv('статус заказа') → «Order status» */
export function translateServerValue(value) {
  const raw = String(value ?? '').trim()
  if (!raw) return raw
  const k = SERVER_IDX.get(fold(raw))
  return k ? translate(k) : raw
}

function makeT() {
  const fn = (key, params) => translate(key, params)
  for (const k of Object.keys(SERVER)) fn[k] = SERVER[k][_lang] != null ? SERVER[k][_lang] : SERVER[k][DEFAULT_LANG]
  fn.sv = translateServerValue
  return fn
}
export const t = makeT()

/* ---------------------------------------------------------------- формат */
const D2 = (v) => (v instanceof Date ? v : new Date(v))
const stripRuYear = (s) => s.replace(/[\s\u00a0]*г\.$/u, '')

export const fmtNumber = (v, opts = {}) => {
  const n = Number(v)
  if (!Number.isFinite(n)) return '—'
  return n.toLocaleString(localeOf(), opts)
}

export const fmtMoney = (v, opts = {}) => {
  // F2: симметрия с Python money() — копейки только при ненулевой дробной части,
  // округление half-up до копеек (Math.round — half-up, Python round() — half-even).
  const num = Number(v) || 0
  const cents = Math.round(num * 100 + Number.EPSILON * Math.sign(num))
  const frac = cents % 100 !== 0
  // целые рубли для компактного режима — half-up от копеек, симметрично в обе стороны
  const n = Math.sign(cents) * Math.round(Math.abs(cents) / 100)
  const plus = opts.plus && cents > 0
  const sign = cents < 0 ? '−' : plus ? '+' : ''
  if (opts.compact) {
    const a = Math.abs(n)
    if (a >= 1_000_000) return `${sign}${fmtNumber(a / 1_000_000, { maximumFractionDigits: 1 })}${_lang === 'ru' ? ' млн' : 'M'}`
    if (a >= 10_000) return `${sign}${fmtNumber(Math.round(a / 1000))}${_lang === 'ru' ? 'к' : 'k'}`
    if (a >= 1000) return `${sign}${fmtNumber(a / 1000, { maximumFractionDigits: 1 })}${_lang === 'ru' ? 'к' : 'k'}`
    return `${sign}${fmtNumber(a)}`
  }
  const s = (Math.abs(cents) / 100).toLocaleString(localeOf(), { minimumFractionDigits: frac ? 2 : 0, maximumFractionDigits: frac ? 2 : 0 })
  return _lang === 'ru' ? `${sign}${s}\u00a0₽` : `${sign}₽${s}`
}

/* moneyShort — компактная сумма для осей и легенд */
export const fmtMoneyShort = (v) => fmtMoney(v, { compact: true })

export const fmtDate = (v, opts) => {
  if (v == null || v === '') return ''
  const x = D2(v)
  if (Number.isNaN(x.getTime())) return ''
  const o = opts || { day: 'numeric', month: _lang === 'ru' ? 'long' : 'short', year: 'numeric' }
  return stripRuYear(x.toLocaleDateString(localeOf(), o))
}
export const fmtTime = (v) => D2(v).toLocaleTimeString(localeOf(), { hour: '2-digit', minute: '2-digit' })
export const fmtWeekday = (v, style = 'long') => D2(v).toLocaleDateString(localeOf(), { weekday: style })

/* «3 дня назад» / «3 days ago» */
export const fmtAgo = (v, ref = Date.now()) => {
  const diff = (ref - D2(v).getTime()) / 1000
  const u = [[60, 'second', 1], [3600, 'minute', 60], [86400, 'hour', 3600], [604800, 'day', 86400]]
  for (const [lim, unit, div] of u) {
    if (diff < lim) return new Intl.RelativeTimeFormat(_lang, { numeric: 'auto' }).format(-Math.floor(diff / div), unit)
  }
  return fmtDate(v)
}

export const fmtList = (arr, opts) => new Intl.ListFormat(_lang, opts || { style: 'narrow', type: 'conjunction' }).format(arr)

