/* Смена языка: localStorage + <html lang> + событие, чтобы подхватили все подписчики */
export function setLangImpl(l) {
  const next = LANGS.includes(l) ? l : DEFAULT_LANG
  _lang = next
  try { store()?.setItem(LS_KEY, next) } catch {}
  try { if (typeof document !== 'undefined') document.documentElement.lang = next } catch {}
  if (typeof window !== 'undefined') window.dispatchEvent(new CustomEvent('i18n:lang', { detail: { lang: next } }))
  return next
}

