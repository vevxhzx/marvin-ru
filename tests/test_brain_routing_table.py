    assert len(TABLE) >= 40, f"таблица сжалась до {len(TABLE)} фраз — страж потерял силу"
    wants = {w for _, w, _ in TABLE}
    assert wants == {"local", "cloud"}, "нужны оба исхода, иначе таблица ничего не проверяет"
